function soc_pdf_attack_timeline_graph(float $x, float $y, array $copy, array $payload): string
{
    $timeline = $payload['attack_timeline'] ?? ['points' => [], 'max' => 0, 'min' => 0];
    $points = array_slice((array)($timeline['points'] ?? []), -14);
    $max = max(1, (int)($timeline['max'] ?? 0));
    $min = max(0, (int)($timeline['min'] ?? 0));
    $cmd = soc_pdf_card($x, $y, 523, 238, '#0ea5e9');
    $cmd .= soc_pdf_text($x + 18, $y + 29, $copy['attack_timeline'], 14, '#111827', true);
    $cmd .= soc_pdf_text($x + 18, $y + 47, $copy['timeline_hint'], 8.5, '#64748b');
    $cmd .= soc_pdf_text($x + 380, $y + 29, $copy['period_min'] . ': ' . $min . '   ' . $copy['period_max'] . ': ' . (int)($timeline['max'] ?? 0), 8.5, '#334155', true);

    $legendX = $x + 350;
    $legendY = $y + 48;
    $legend = [
        ['label' => 'SQLi', 'color' => '#dc2626'],
        ['label' => 'XSS', 'color' => '#7c3aed'],
        ['label' => 'Brute Force', 'color' => '#f59e0b'],
    ];
    foreach ($legend as $index => $item) {
        $lx = $legendX + ($index * 56);
        $cmd .= soc_pdf_rect($lx, $legendY - 8, 8, 8, $item['color']);
        $cmd .= soc_pdf_text($lx + 12, $legendY, $item['label'], 7.5, '#334155', true);
    }

    $chartX = $x + 36;
    $chartY = $y + 72;
    $chartW = 455;
    $chartH = 118;
    for ($line = 0; $line <= 4; $line++) {
        $lineY = $chartY + ($line * ($chartH / 4));
        $cmd .= soc_pdf_rect($chartX, $lineY, $chartW, 0.5, '#e2e8f0');
    }

    $count = max(1, count($points));
    $gap = $count > 10 ? 8 : 14;
    $barW = min(26, max(10, ($chartW - (($count - 1) * $gap)) / $count));
    $usedW = ($count * $barW) + (($count - 1) * $gap);
    $startX = $chartX + max(0, ($chartW - $usedW) / 2);
    $segments = [
        'sqli' => '#dc2626',
        'xss' => '#7c3aed',
        'bruteforce' => '#f59e0b',
    ];

    foreach ($points as $index => $point) {
        $barX = $startX + ($index * ($barW + $gap));
        $cmd .= soc_pdf_rect($barX, $chartY, $barW, $chartH, '#eef2f8');
        $bottom = $chartY + $chartH;
        foreach ($segments as $key => $color) {
            $value = (int)($point[$key] ?? 0);
            if ($value <= 0) {
                continue;
            }
            $height = max(2, ($value / $max) * $chartH);
            $top = $bottom - $height;
            $cmd .= soc_pdf_rect($barX, $top, $barW, $height, $color);
            $bottom = $top;
        }
        $cmd .= soc_pdf_text($barX - 4, $chartY + $chartH + 15, (string)($point['label'] ?? ''), 6.8, '#64748b');
    }

    $cmd .= soc_pdf_text($x + 18, $y + 218, $copy['dominant_attack'] . ': ' . $payload['dominant_attack']['label'] . ' (' . $payload['dominant_attack']['percent'] . '%)', 9, '#1d4ed8', true);
    return $cmd;
}

function soc_pdf_build_document(array $pages): string
{
    $pageCount = count($pages);
    $pageStart = 5;
    $contentStart = $pageStart + $pageCount;
    $objects = [
        1 => '<< /Type /Catalog /Pages 2 0 R >>',
        3 => '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        4 => '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    ];
    $kids = [];

    foreach ($pages as $index => $content) {
        $pageId = $pageStart + $index;
        $contentId = $contentStart + $index;
        $kids[] = $pageId . ' 0 R';
        $objects[$pageId] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents $contentId 0 R >>";
        $objects[$contentId] = "<< /Length " . strlen($content) . " >>\nstream\n" . $content . "\nendstream";
    }

    $objects[2] = '<< /Type /Pages /Kids [' . implode(' ', $kids) . '] /Count ' . $pageCount . ' >>';
    ksort($objects);

    $pdf = "%PDF-1.4\n";
    $offsets = [0];
    foreach ($objects as $id => $object) {
        $offsets[$id] = strlen($pdf);
        $pdf .= $id . " 0 obj\n" . $object . "\nendobj\n";
    }
    $xref = strlen($pdf);
    $pdf .= "xref\n0 " . (count($objects) + 1) . "\n";
    $pdf .= "0000000000 65535 f \n";
    for ($i = 1; $i <= count($objects); $i++) {
        $pdf .= sprintf("%010d 00000 n \n", $offsets[$i]);
    }
    $pdf .= "trailer\n<< /Size " . (count($objects) + 1) . " /Root 1 0 R >>\nstartxref\n" . $xref . "\n%%EOF";
    return $pdf;
}

function soc_send_pdf_report(array $filters, array $options): void
{
    $copy = soc_report_copy();
    $payload = soc_report_payload($filters, $options);
    $stats = $payload['stats'];
    $detection = $payload['detection'];
    $pages = [];
    $page = 0;
    $content = '';
    $y = 0.0;

    $startPage = function () use (&$pages, &$page, &$content, &$y, $copy, $filters, $payload): void {
        if ($page > 0) {
            $pages[] = $content;
        }
        $page++;
        $content = soc_pdf_header($copy, $filters, $payload, $page);
        $y = 132;
    };

    $ensure = function (float $height) use (&$startPage, &$y): void {
        if ($y + $height > 795) {
            $startPage();
        }
    };

    $startPage();

    $cardW = 123;
    $content .= soc_pdf_stat_card(36, $y, $cardW, $copy['total_alerts'], (string)$stats['total'], '#2563eb');
    $content .= soc_pdf_stat_card(169, $y, $cardW, $copy['critical'], (string)($stats['severity']['CRITICAL'] ?? 0), '#dc2626');
    $content .= soc_pdf_stat_card(302, $y, $cardW, $copy['high'], (string)($stats['severity']['HIGH'] ?? 0), '#f59e0b');
    $content .= soc_pdf_stat_card(435, $y, $cardW, $copy['global_score'], $detection['score_global'] . ' / ' . $detection['score_level'], '#7c3aed');
    $y += 98;

    $content .= soc_pdf_card(36, $y, 523, 128, '#2563eb');
    $content .= soc_pdf_text(54, $y + 28, $copy['attack_percentages'], 14, '#111827', true);
    $dominant = $payload['dominant_attack'];
    $content .= soc_pdf_text(370, $y + 28, $copy['dominant_attack'] . ': ' . $dominant['label'] . ' (' . $dominant['percent'] . '%)', 9, '#334155', true);
    $rowY = $y + 55;
    foreach ($payload['attack_percentages'] as $item) {
        $content .= soc_pdf_text(54, $rowY + 8, $item['label'], 10, '#111827', true);
        $content .= soc_pdf_bar(150, $rowY, 270, (float)$item['percent'], $item['color']);
        $content .= soc_pdf_text(435, $rowY + 8, $item['count'] . ' (' . $item['percent'] . '%)', 9, '#334155', true);
        $rowY += 25;
    }
    $y += 152;

    $content .= soc_pdf_text(36, $y, $copy['detected_cases'], 15, '#111827', true);
    $y += 18;

    if (!$payload['cases']) {
        $content .= soc_pdf_card(36, $y, 523, 58, '#94a3b8');
        $content .= soc_pdf_text(54, $y + 34, $copy['no_alerts'], 11, '#334155', true);
        $y += 78;
    }

    foreach ($payload['cases'] as $case) {
        $incidentLines = soc_pdf_wrap_text($case['incident'], 474, 9);
        $responseLines = [];
        foreach ($case['responses'] as $response) {
            foreach (soc_pdf_wrap_text('- ' . $response, 462, 8.5) as $line) {
                $responseLines[] = $line;
            }
        }
        $improvementLines = [];
        foreach ($case['improvements'] as $improvement) {
            foreach (soc_pdf_wrap_text('- ' . $improvement, 462, 8.5) as $line) {
                $improvementLines[] = $line;
            }
        }

        $caseHeight = 136 + (count($incidentLines) * 11);
        if ($options['include_response'] && $responseLines) {
            $caseHeight += 22 + (count($responseLines) * 11);
        }
        if ($improvementLines) {
            $caseHeight += 22 + (count($improvementLines) * 11);
        }
        $caseHeight = max(178, $caseHeight);

        $ensure($caseHeight + 18);
        $accent = soc_pdf_severity_color((string)$case['severity']);
        $content .= soc_pdf_card(36, $y, 523, $caseHeight, $accent);
        $content .= soc_pdf_text(54, $y + 27, $case['label'] . ' - ' . $case['count'] . ' ' . $copy['cases'], 13, '#111827', true);
        $content .= soc_pdf_text(398, $y + 27, soc_severity_label($case['severity']), 10, $accent, true);
        $content .= soc_pdf_text(54, $y + 47, $copy['latest_seen'] . ': ' . $case['latest_seen'], 8.5, '#64748b');
        if ($case['sources']) {
            $content .= soc_pdf_text(54, $y + 63, $copy['main_sources'] . ': ' . implode(', ', $case['sources']), 8.5, '#64748b');
        }
        if ($options['include_mitre']) {
            $mitreParts = array_values(array_filter([$case['mitre_id'], $case['mitre_tactic'], $case['mitre_technique']]));
            if ($mitreParts) {
                $content .= soc_pdf_text(54, $y + 81, $copy['mitre_detected'] . ': ' . implode(' - ', $mitreParts), 8.5, '#1d4ed8', true);
            }
        }

        $yy = $y + 101;
        $content .= soc_pdf_text(54, $yy, $copy['incident_analysis'], 9, '#111827', true);
        $yy += 14;
        foreach ($incidentLines as $line) {
            $content .= soc_pdf_text(66, $yy, $line, 8.5, '#334155');
            $yy += 11;
        }

        if ($options['include_response'] && $responseLines) {
            $yy += 8;
            $content .= soc_pdf_text(54, $yy, $copy['responses'], 9, '#111827', true);
            $yy += 14;
            foreach ($responseLines as $line) {
                $content .= soc_pdf_text(66, $yy, $line, 8.5, '#334155');
                $yy += 11;
            }
        }

        if ($improvementLines) {
            $yy += 8;
            $content .= soc_pdf_text(54, $yy, $copy['improvements'], 9, '#111827', true);
            $yy += 14;
            foreach ($improvementLines as $line) {
                $content .= soc_pdf_text(66, $yy, $line, 8.5, '#334155');
                $yy += 11;
            }
        }

        $y += $caseHeight + 18;
    }

    $ensure(262);
    $content .= soc_pdf_attack_timeline_graph(36, $y, $copy, $payload);
    $y += 262;

    $pages[] = $content;
    $pdf = soc_pdf_build_document($pages);

    header('Content-Type: application/pdf');
    header('Content-Disposition: attachment; filename="' . $copy['filename'] . '"');
    header('Content-Length: ' . strlen($pdf));
    echo $pdf;
    exit;
}

