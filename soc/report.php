function soc_report_case_key(array $alert): string
{
    $label = strtolower((string)($alert['attack_label'] ?? $alert['attack_type'] ?? ''));
    if (str_contains($label, 'sql')) {
        return 'SQLi';
    }
    if (str_contains($label, 'xss') || str_contains($label, 'cross-site')) {
        return 'XSS';
    }
    if (str_contains($label, 'brute')) {
        return 'BruteForce';
    }
    return '';
}

function soc_report_case_label(string $key): string
{
    return [
        'SQLi' => 'SQLi',
        'XSS' => 'XSS',
        'BruteForce' => 'Brute Force',
    ][$key] ?? $key;
}

function soc_report_case_recommendation(string $key, array $recommendations): array
{
    $lang = soc_current_language();
    $data = $recommendations[$key][$lang] ?? $recommendations[$key]['fr'] ?? [];
    return [
        'incident' => (string)($data['incident'] ?? ''),
        'responses' => array_values(array_filter((array)($data['responses'] ?? []))),
        'improvements' => array_values(array_filter((array)($data['improvements'] ?? []))),
    ];
}

function soc_report_cases(array $alerts): array
{
    $recommendations = soc_report_recommendations();
    $mitreMap = soc_mitre_map();
    $cases = [];

    foreach ($alerts as $alert) {
        $key = soc_report_case_key($alert);
        if ($key === '') {
            continue;
        }

        if (!isset($cases[$key])) {
            $mitre = $mitreMap[$key] ?? [];
            $cases[$key] = [
                'key' => $key,
                'label' => soc_report_case_label($key),
                'count' => 0,
                'severity' => strtoupper((string)($alert['severity'] ?? $mitre['severity'] ?? '')),
                'latest_seen' => $alert['timestamp'] ?? '',
                'sources' => [],
                'mitre_id' => (string)($alert['mitre_id'] ?? $mitre['mitre_id'] ?? ''),
                'mitre_tactic' => (string)($alert['mitre_tactic'] ?? $mitre['tactic'] ?? ''),
                'mitre_technique' => (string)($alert['mitre_technique'] ?? $mitre['technique'] ?? ''),
            ] + soc_report_case_recommendation($key, $recommendations);
        }

        $cases[$key]['count']++;
        if (soc_severity_rank((string)($alert['severity'] ?? '')) > soc_severity_rank((string)$cases[$key]['severity'])) {
            $cases[$key]['severity'] = strtoupper((string)$alert['severity']);
        }
        if (!empty($alert['timestamp'])) {
            $cases[$key]['latest_seen'] = $alert['timestamp'];
        }
        if (!empty($alert['source_ip'])) {
            $cases[$key]['sources'][(string)$alert['source_ip']] = true;
        }
    }

    foreach ($cases as &$case) {
        $case['sources'] = array_slice(array_keys($case['sources']), 0, 5);
    }
    unset($case);

    return array_values($cases);
}

function soc_report_attack_percentages(array $stats): array
{
    $total = max(0, (int)($stats['total'] ?? 0));
    $items = [
        ['key' => 'sqli', 'label' => 'SQLi', 'count' => (int)($stats['sqli'] ?? 0), 'color' => '#dc2626'],
        ['key' => 'xss', 'label' => 'XSS', 'count' => (int)($stats['xss'] ?? 0), 'color' => '#7c3aed'],
        ['key' => 'bruteforce', 'label' => 'Brute Force', 'count' => (int)($stats['brute_force'] ?? 0), 'color' => '#f59e0b'],
    ];

    foreach ($items as &$item) {
        $item['percent'] = $total > 0 ? round(($item['count'] / $total) * 100, 1) : 0.0;
    }
    unset($item);

    return $items;
}

function soc_report_dominant_attack(array $percentages): array
{
    $dominant = ['label' => '-', 'count' => 0, 'percent' => 0.0, 'color' => '#2563eb'];
    foreach ($percentages as $item) {
        if ((int)$item['count'] > (int)$dominant['count']) {
            $dominant = $item;
        }
    }
    return $dominant;
}

function soc_report_attack_timeline(array $alerts, array $filters): array
{
    $from = DateTime::createFromFormat('Y-m-d H:i:s', (string)$filters['date_from'] . ' 00:00:00') ?: new DateTime('-6 days');
    $to = DateTime::createFromFormat('Y-m-d H:i:s', (string)$filters['date_to'] . ' 23:59:59') ?: new DateTime();
    if ($to < $from) {
        [$from, $to] = [$to, $from];
    }

    $days = (int)$from->diff($to)->format('%a');
    $group = $days > 31 ? 'month' : 'day';
    $periods = [];
    $cursor = clone $from;
    $end = clone $to;

    if ($group === 'month') {
        $cursor->modify('first day of this month')->setTime(0, 0, 0);
        $end->modify('first day of this month')->setTime(0, 0, 0);
    } else {
        $cursor->setTime(0, 0, 0);
        $end->setTime(0, 0, 0);
    }

    while ($cursor <= $end) {
        $key = $cursor->format($group === 'month' ? 'Y-m' : 'Y-m-d');
        $periods[$key] = [
            'key' => $key,
            'label' => $cursor->format($group === 'month' ? 'm/Y' : 'd/m'),
            'sqli' => 0,
            'xss' => 0,
            'bruteforce' => 0,
            'total' => 0,
        ];
        $cursor->modify($group === 'month' ? '+1 month' : '+1 day');
    }

    foreach ($alerts as $alert) {
        try {
            $date = new DateTime((string)($alert['timestamp'] ?? ''));
        } catch (Exception $exception) {
            continue;
        }

        $key = $date->format($group === 'month' ? 'Y-m' : 'Y-m-d');
        if (!isset($periods[$key])) {
            continue;
        }

        $case = soc_report_case_key($alert);
        $token = [
            'SQLi' => 'sqli',
            'XSS' => 'xss',
            'BruteForce' => 'bruteforce',
        ][$case] ?? '';

        if ($token === '') {
            continue;
        }

        $periods[$key][$token]++;
        $periods[$key]['total']++;
    }

    $points = array_values($periods);
    $totals = array_map(static fn(array $point): int => (int)$point['total'], $points);
    $nonZero = array_values(array_filter($totals, static fn(int $total): bool => $total > 0));

    return [
        'group' => $group,
        'points' => $points,
        'max' => $totals ? max($totals) : 0,
        'min' => $nonZero ? min($nonZero) : 0,
    ];
}

function soc_report_payload(array $filters, array $options): array
{
    $rawAlerts = soc_fetch_alert_history($filters);
    $alerts = array_map('soc_alert_payload', $rawAlerts);
    $stats = soc_dashboard_stats($filters);
    $attackPercentages = soc_report_attack_percentages($stats);
    return [
        'stats' => $stats,
        'alerts' => $alerts,
        'cases' => soc_report_cases($alerts),
        'detection' => soc_detection_status(),
        'attack_percentages' => $attackPercentages,
        'dominant_attack' => soc_report_dominant_attack($attackPercentages),
        'attack_timeline' => soc_report_attack_timeline($rawAlerts, $filters),
    ];
}

function soc_report_text_lines(array $filters, array $options): array
{
    $copy = soc_report_copy();
    $payload = soc_report_payload($filters, $options);
    $stats = $payload['stats'];
    $detection = $payload['detection'];
    $lines = [
        $copy['period'] . ': ' . $filters['date_from'] . ' - ' . $filters['date_to'],
        $copy['generated_at'] . ': ' . date('d/m/Y H:i:s'),
        '',
        $copy['summary'],
        $copy['total_alerts'] . ': ' . $stats['total'],
        $copy['global_score'] . ': ' . $detection['score_global'] . ' / ' . $detection['score_level'],
        'SQLi: ' . $stats['sqli'],
        'XSS: ' . $stats['xss'],
        'Brute Force: ' . $stats['brute_force'],
        $copy['critical'] . ': ' . ($stats['severity']['CRITICAL'] ?? 0),
        $copy['high'] . ': ' . ($stats['severity']['HIGH'] ?? 0),
        $copy['medium'] . ': ' . ($stats['severity']['MEDIUM'] ?? 0),
        $copy['low'] . ': ' . ($stats['severity']['LOW'] ?? 0),
        '',
        $copy['attack_percentages'],
    ];

    foreach ($payload['attack_percentages'] as $item) {
        $lines[] = $item['label'] . ': ' . $item['count'] . ' (' . $item['percent'] . '%)';
    }

    $lines[] = $copy['dominant_attack'] . ': ' . $payload['dominant_attack']['label'] . ' (' . $payload['dominant_attack']['percent'] . '%)';
    $lines[] = '';
    $lines[] = $copy['detected_cases'];

    if (!$payload['cases']) {
        $lines[] = $copy['no_alerts'];
        return $lines;
    }

    foreach ($payload['cases'] as $case) {
        $lines[] = '';
        $lines[] = $case['label'] . ': ' . $case['count'] . ' ' . $copy['cases'] . ' | ' . $copy['severity'] . ': ' . soc_severity_label($case['severity']);
        $lines[] = $copy['latest_seen'] . ': ' . $case['latest_seen'];
        if ($case['sources']) {
            $lines[] = $copy['main_sources'] . ': ' . implode(', ', $case['sources']);
        }
        if ($options['include_mitre']) {
            $mitreParts = array_values(array_filter([$case['mitre_id'], $case['mitre_tactic'], $case['mitre_technique']]));
            if ($mitreParts) {
                $lines[] = $copy['mitre_detected'] . ': ' . implode(' - ', $mitreParts);
            }
        }
        if ($case['incident'] !== '') {
            $lines[] = $copy['incident_analysis'] . ': ' . $case['incident'];
        }
        if ($options['include_response'] && $case['responses']) {
            $lines[] = $copy['responses'] . ':';
            foreach ($case['responses'] as $response) {
                $lines[] = '- ' . $response;
            }
        }
        if ($case['improvements']) {
            $lines[] = $copy['improvements'] . ':';
            foreach ($case['improvements'] as $improvement) {
                $lines[] = '- ' . $improvement;
            }
        }
    }

    return $lines;
}

function soc_pdf_escape(string $text): string
{
    $text = str_replace(["\r", "\n", "\t"], ' ', $text);
    if (function_exists('iconv')) {
        $converted = iconv('UTF-8', 'Windows-1252//TRANSLIT', $text);
        if ($converted !== false) {
            $text = $converted;
        }
    }
    return str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $text);
}

function soc_wrap_report_line(string $line, int $limit = 94): array
{
    if ($line === '') {
        return [''];
    }
    $wrapped = wordwrap($line, $limit, "\n", true);
    return explode("\n", $wrapped);
}

function soc_pdf_rgb(string $hex, string $operator): string
{
    $hex = ltrim($hex, '#');
    if (strlen($hex) === 3) {
        $hex = $hex[0] . $hex[0] . $hex[1] . $hex[1] . $hex[2] . $hex[2];
    }
    $r = hexdec(substr($hex, 0, 2)) / 255;
    $g = hexdec(substr($hex, 2, 2)) / 255;
    $b = hexdec(substr($hex, 4, 2)) / 255;
    return sprintf('%.4f %.4f %.4f %s', $r, $g, $b, $operator);
}

function soc_pdf_rect(float $x, float $y, float $w, float $h, string $fill, ?string $stroke = null, float $lineWidth = 1): string
{
    $py = 842 - $y - $h;
    $cmd = 'q ' . soc_pdf_rgb($fill, 'rg') . ' ';
    if ($stroke !== null) {
        $cmd .= soc_pdf_rgb($stroke, 'RG') . ' ' . $lineWidth . ' w ';
    }
    $cmd .= sprintf('%.2f %.2f %.2f %.2f re %s Q', $x, $py, $w, $h, $stroke === null ? 'f' : 'B');
    return $cmd . "\n";
}

function soc_pdf_text(float $x, float $y, string $text, float $size = 10, string $color = '#111827', bool $bold = false): string
{
    $font = $bold ? 'F2' : 'F1';
    $py = 842 - $y;
    return 'BT /' . $font . ' ' . $size . ' Tf ' . soc_pdf_rgb($color, 'rg') . ' ' .
        sprintf('%.2f %.2f Td ', $x, $py) . '(' . soc_pdf_escape($text) . ") Tj ET\n";
}

function soc_pdf_wrap_text(string $text, float $maxWidth, float $size): array
{
    $text = trim((string)preg_replace('/\s+/', ' ', $text));
    if ($text === '') {
        return [];
    }
    $chars = max(18, (int)floor($maxWidth / max(4.5, $size * 0.52)));
    return explode("\n", wordwrap($text, $chars, "\n", true));
}

function soc_pdf_multiline(float $x, float $y, string $text, float $maxWidth, float $size, string $color, bool $bold = false, float $lineHeight = 12): array
{
    $lines = soc_pdf_wrap_text($text, $maxWidth, $size);
    $cmd = '';
    foreach ($lines as $index => $line) {
        $cmd .= soc_pdf_text($x, $y + ($index * $lineHeight), $line, $size, $color, $bold);
    }
    return [$cmd, count($lines) * $lineHeight];
}

